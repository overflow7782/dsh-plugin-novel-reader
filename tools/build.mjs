// 零依赖构建：把 src 下的 ES 模块按依赖顺序拼进 DSH 的 __ModuleLoader__ 包装里，输出 lib/client.js。
// 源码保持 ES 模块是为了让 core/ 能直接被 node --test 引用；拼接时去掉 import 行和 export 关键字。
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const ORDER = [
  'core/text.js',
  'core/zip.js',
  'core/html.js',
  'core/epub.js',
  'core/book.js',
  'core/glass.js',
  'core/peek-geom.js',
  'client/db.js',
  'client/settings.js',
  'client/i18n.js',
  'client/state.js',
  'client/icons.js',
  'client/styles.js',
  'client/ui-shared.js',
  'client/dock-order.js',
  'client/ui-settings.js',
  'client/ui-reader.js',
  'client/ui-peek.js',
  'client/nav-icon.js',
  'client/apply.js',
];

const declared = new Map();
const parts = ORDER.map((file) => {
  const source = readFileSync(join(root, 'src', file), 'utf8')
    .replace(/^import\s[^;]*;\s*$/gm, '')
    .replace(/^\/\* global [^*]*\*\/\s*$/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|class)/gm, '');
  for (const m of source.matchAll(/^(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    const prev = declared.get(m[1]);
    if (prev !== undefined) throw new Error(`top-level name "${m[1]}" declared in both ${prev} and ${file}`);
    declared.set(m[1], file);
  }
  if (/^\s*export\s/m.test(source)) throw new Error(`${file}: unsupported export form`);
  return `// ---- src/${file}\n${source.trim()}\n`;
});

const out = `// ${pkg.name} ${pkg.version} — generated by tools/build.mjs from src/, do not edit.
window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {
"use strict";
var module = { exports: {} };
const React = require("react");
const { createPortal } = require("react-dom");
const h = React.createElement;

${parts.join('\n')}
module.exports = { inject, apply };
return module.exports;
}});
`;

writeFileSync(join(root, 'lib', 'client.js'), out);
console.log(`lib/client.js written (${(out.length / 1024).toFixed(1)} KB, ${declared.size} top-level names)`);
